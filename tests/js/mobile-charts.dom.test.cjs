const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const dom = new JSDOM('<html lang="en"><script id="salepro-mobile-config" type="application/json">{"currency":"XOF","precision":2,"strings":{}}</script><div class="pie-chart"><canvas id="pie"></canvas></div><div class="line-chart"><canvas id="line"></canvas></div></html>',{url:'https://pos.test/dashboard',runScripts:'dangerously',pretendToBeVisual:true});
const w=dom.window, media={matches:true,addEventListener(){}};
w.matchMedia=()=>media;
function chart(id,type,data) {return {canvas:w.document.getElementById(id),config:{type},data,options:{maintainAspectRatio:true,legend:{position:'right'},scales:{xAxes:[{ticks:{maxRotation:45}}]}},resize(){},update(){}};}
const pie=chart('pie','doughnut',{labels:['Revenue','Purchases','Expenses'],datasets:[{data:[100,20,10]}]});
const line=chart('line','line',{labels:['Jan','Feb'],datasets:[{label:'Sales',data:[12,3]}]});
const original=JSON.stringify([pie.data,line.data]);
w.Chart={instances:{pie,line}};
w.eval(fs.readFileSync(path.resolve(__dirname,'../../public/js/salepro-mobile.js'),'utf8'));
assert.equal(pie.options.legend.position,'bottom');
assert.equal(line.options.scales.xAxes[0].ticks.maxTicksLimit,6);
assert.equal(line.options.maintainAspectRatio,false);
assert.equal(w.document.querySelectorAll('.sp-chart-summary').length,2);
assert(pie.canvas.getAttribute('aria-label').includes('Revenue: 100 XOF'));
assert(pie.canvas.getAttribute('aria-label').includes('Purchases: 20 XOF'));
assert.equal(JSON.stringify([pie.data,line.data]),original,'presentation must preserve chart source values');
pie.data.datasets[0].data[0]=200;
w.SaleProMobile.decorate();
assert(pie.canvas.getAttribute('aria-label').includes('Revenue: 200 XOF'));
assert.equal(w.document.querySelectorAll('.sp-chart-summary').length,2,'repeated decoration must not duplicate summaries');
media.matches=false;w.SaleProMobile.decorate();
assert.equal(line.options.scales.xAxes[0].ticks.maxRotation,45);
assert.equal(pie.options.legend.position,'right');
assert.equal(line.options.maintainAspectRatio,true);
dom.window.close();
console.log('PASS chart summaries, accessible category values, source preservation, refreshed values and restored desktop settings');
