const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '../..');
const dom = new JSDOM('<script id="salepro-mobile-config" type="application/json">{"strings":{"details":"Details","less":"Less","previous":"Previous","next":"Next","page":"Page","records":"records"}}</script><table id="records"><thead><tr><th>Reference</th><th>Date</th><th>Total</th><th>Status</th><th>Extra</th><th>Customer</th><th>Actions</th></tr></thead></table>', {url:'https://pos.test/sales',runScripts:'dangerously',pretendToBeVisual:true,beforeParse(w){w.matchMedia=()=>({matches:true,addEventListener(){}});}});
const w=dom.window;
w.eval(fs.readFileSync(path.join(root,'public/vendor/jquery/jquery.min.js'),'utf8'));
w.eval(fs.readFileSync(path.join(root,'public/vendor/datatable/jquery.dataTables.min.js'),'utf8'));
const api=w.jQuery('#records').DataTable({data:Array.from({length:45},(_,i)=>['Record '+i,'2026-11-15','100','Unpaid','Detail','Customer '+i,'Edit']),pageLength:10});
w.eval(fs.readFileSync(path.join(root,'public/js/salepro-mobile.js'),'utf8'));
const nav=w.document.querySelector('.sp-pagination');
assert(nav); assert.equal(nav.querySelector('span').textContent,'Page 1 / 5 · 45 records');
assert.equal(nav.querySelector('button').disabled,true);
nav.querySelectorAll('button')[1].click(); w.SaleProMobile.decorate();
assert.equal(api.page(),1);
api.search('"Record 1"').draw(); w.SaleProMobile.decorate();
assert.equal(nav.querySelector('span').textContent,'Page 1 / 2 · 11 records');
nav.querySelectorAll('button')[1].click(); w.SaleProMobile.decorate();
assert.equal(nav.querySelector('span').textContent,'Page 2 / 2 · 11 records');
assert.equal(nav.querySelectorAll('button')[1].disabled,true);
nav.querySelector('select').value='25'; nav.querySelector('select').dispatchEvent(new w.Event('change'));
w.SaleProMobile.decorate();
assert.equal(api.search(),'"Record 1"'); assert.equal(api.page.info().recordsDisplay,11); assert.equal(api.page.len(),25);
assert(!w.document.querySelector('#records tbody td:nth-child(6)').classList.contains('sp-secondary'),'Customer must remain visible on mobile cards');
assert.equal(w.document.querySelectorAll('.sp-pagination').length,1);
api.destroy();
w.jQuery('#records').DataTable({pageLength:10});
w.SaleProMobile.decorate();
assert.equal(w.document.querySelectorAll('.sp-pagination').length,1,'filter workflows that rebuild DataTables must retain one functional pagination control');
assert.equal(w.document.querySelector('.sp-pagination button').disabled,true);
dom.window.close();
console.log('PASS real DataTables pagination, filtered counts, boundaries, page size, preserved search and customer priority');
