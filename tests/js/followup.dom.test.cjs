const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname, '../..');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
(async () => {
    const dom = new JSDOM('<html lang="fr"><form id="product-filter-form"><select id="category_id"><option value="0">All categories</option><option value="2">Food</option></select><select id="warehouse_id"><option value="0">All warehouses</option><option value="1">Main warehouse</option></select></form><strong id="stock-scope"></strong><form id="quick-product-form"><input name="code"><button type="button" data-generate-code="/products/gencode">Generate</button><span data-code-status></span></form></html>', {url:'https://pos.test/products',runScripts:'dangerously'});
    const w=dom.window;
    w.eval(fs.readFileSync(path.join(root,'public/js/product-listing.js'),'utf8'));
    const calls=[], table={ajax:{reload(...args){calls.push(args);}},search:'rice'};
    w.SaleProInventory.bind(table);
    const category=w.document.getElementById('category_id'), warehouse=w.document.getElementById('warehouse_id');
    category.value='2'; category.dispatchEvent(new w.Event('change'));
    category.value='0'; category.dispatchEvent(new w.Event('change'));
    warehouse.value='1'; warehouse.dispatchEvent(new w.Event('change'));
    assert.equal(calls.length,3); assert.deepEqual(calls[0],[null,true]); assert.equal(table.search,'rice');
    assert.equal(w.document.getElementById('stock-scope').textContent,'Main warehouse');
    const quantity=w.SaleProInventory.quantity(5.5,'display',{stock_status:'low_stock'},{stock_low:'Stock faible'});
    assert(quantity.includes('Stock faible')); assert(quantity.includes('<strong>5,5</strong>'));
    assert.equal(w.SaleProInventory.quantity(5.5,'sort',{},{}),5.5);
    w.eval(fs.readFileSync(path.join(root,'public/js/quick-product.js'),'utf8'));
    const pending=[]; w.fetch=()=>new Promise(resolve=>pending.push(resolve));
    const form=w.document.getElementById('quick-product-form'), code=form.querySelector('input'), button=form.querySelector('button');
    w.SaleProQuickProduct(form,{replace_code:'Replace?',loading:'Loading',code_generated:'Generated',code_preserved:'Preserved',search_error:'Failed'});
    code.value='MANUAL'; w.confirm=()=>false; button.click(); assert.equal(pending.length,0); assert.equal(code.value,'MANUAL');
    code.value='';button.click(); assert(button.disabled);
    pending.shift()({ok:true,text:async()=> '12345678'});await tick();assert.equal(code.value,'12345678');assert(!button.disabled);
    w.confirm=()=>true; button.click();code.value='EDITED-WHILE-WAITING';pending.shift()({ok:true,text:async()=> '87654321'});await tick();
    assert.equal(code.value,'EDITED-WHILE-WAITING');assert.equal(form.querySelector('[data-code-status]').textContent,'Preserved');
    button.click();pending.shift()({ok:false});await tick();assert.equal(code.value,'EDITED-WHILE-WAITING');assert(!button.disabled);
    button.click();form.reset();pending.shift()({ok:true,text:async()=> '11223344'});await tick();
    assert.equal(code.value,'','a saved/reset modal must reject an old generation response');assert(!button.disabled);
    dom.window.close();
    const blade=fs.readFileSync(path.join(root,'resources/views/backend/index.blade.php'),'utf8');
    const dashboard=new JSDOM(blade);
    for(const id of ['cashFlow','transactionChart','saleChart']) assert(dashboard.window.document.getElementById(id).closest('.sp-chart-frame'),id+' needs a measured chart frame');
    dashboard.window.close();
    const css=fs.readFileSync(path.join(root,'public/css/salepro-mobile.css'),'utf8');
    assert(!css.includes('.dashboard-counts .row{display:grid'),'KPI grid must not apply to chart rows');
    assert(css.includes('--sp-visual-height'),'modal must follow the visual viewport');
    console.log('PASS category/all-category reloads, preserved search, warehouse caption, fractional stock, consent-aware code generation, async edits and dashboard frame contracts');
})().catch(error=>{console.error(error);process.exitCode=1;});
