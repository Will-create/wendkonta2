const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const root = path.resolve(__dirname,'../..');
const config={strings:{pending:'Saving',offline:'Connect to save',unsaved:'Review the form'}};
const dom=new JSDOM(`<!doctype html><script id="salepro-mobile-config" type="application/json">${JSON.stringify(config)}</script><form action="/products/update" method="post"><input name="id" value="1"><button type="submit">Save product</button></form>`,{url:'https://pos.test/products/1/edit',runScripts:'dangerously',pretendToBeVisual:true,beforeParse(w){w.matchMedia=()=>({matches:true,addEventListener(){}});Object.defineProperty(w.navigator,'onLine',{value:true,configurable:true});}});
const w=dom.window;
const errors=[];
w.addEventListener('error',e=>errors.push(e.message));
w.eval(fs.readFileSync(path.join(root,'public/vendor/jquery/jquery.min.js'),'utf8'));
w.eval(fs.readFileSync(path.join(root,'public/js/salepro-mobile.js'),'utf8'));
const $=w.jQuery;
const form=w.document.querySelector('form');
const button=form.querySelector('button');
const token=()=>form.querySelector('[name=operation_token]').value;
const requests=[];
$.ajaxTransport('+*',()=>({send(headers,complete){requests.push(complete);},abort(){}}));
function save(){return $.ajax({url:'/products/update',method:'POST',data:$(form).serialize()});}
const originalToken=token();
save();
assert.equal(requests.length,1);
assert.equal(form.dataset.spPending,'true');
const blocked=save();
assert.equal(blocked.status,0);
assert.equal(requests.length,1,'duplicate request must never reach transport');
assert.equal(form.dataset.spPending,'true','blocked duplicate must not unlock the active request');
button.disabled=true;button.innerHTML='Saving...';
requests[0](422,'Unprocessable Entity',{text:JSON.stringify({errors:{name:['Enter a product name.']}})},'Content-Type: application/json\r\n');
assert.equal(form.dataset.spPending,'false');
assert.equal(form.dataset.spDirty,'true');
assert.equal(token(),originalToken,'failed request must retain its retry token');
assert.equal(button.disabled,false);
assert.equal(button.textContent,'Save product');
assert.equal(form.querySelector('.sp-submit-feedback').textContent,'Enter a product name.');
save();
requests[1](200,'OK',{text:'1'},'Content-Type: text/plain\r\nX-SalePro-Operation: complete\r\n');
assert.notEqual(token(),originalToken,'successful write starts a new submission');
assert.equal(form.dataset.spPending,'false');
Object.defineProperty(w.navigator,'onLine',{value:false,configurable:true});
save();
assert.equal(requests.length,2,'offline request must not reach transport');
assert.equal(form.querySelector('.sp-submit-feedback').textContent,'Connect to save');
let directClick=false;
button.addEventListener('click',()=>{directClick=true;});
button.click();
assert.equal(directClick,false,'offline guard must precede legacy direct-click AJAX handlers');
assert.deepEqual(errors,[]);
dom.window.close();
console.log('PASS AJAX duplicate/offline guards, active-request preservation, validation recovery and retry tokens');
